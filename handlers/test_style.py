@router.message(Command("test_style"))
async def cmd_test_style(message: Message, state: FSMContext):
    user = await get_user_by_tg_id(message.from_user.id)
    if not user:
        await message.answer("Сначала заполните анкету через /start")
        return

    questions = mentee_questions if user.is_student else mentor_questions
    await state.update_data(questions=questions, current_q=0)
    await state.set_state(WorkStyleTest.q1)
    await ask_question(message, state, 0, questions)

async def ask_question(message: Message, state: FSMContext, index: int, questions: list):
    q = questions[index]
    kb = InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text=opt[0], callback_data=f"style_{index}_{opt[1]}")] for opt in q["options"]
    ])
    await message.answer(q["text"], reply_markup=kb)

@router.callback_query(lambda c: c.data.startswith("style_"))
async def process_answer(callback: CallbackQuery, state: FSMContext):
    parts = callback.data.split("_")
    q_index = int(parts[1])
    chosen_type = parts[2]

    data = await state.get_data()
    counts = data.get('style_counts', {})
    counts[chosen_type] = counts.get(chosen_type, 0) + 1
    await state.update_data(style_counts=counts)

    questions = data.get('questions')
    next_index = q_index + 1
    if next_index < len(questions):
        await ask_question(callback.message, state, next_index, questions)
    else:
        if not counts:
            result = "Не определен"
        else:
            result = max(counts, key=counts.get)
        await update_user_work_style(callback.from_user.id, result)
        await callback.message.edit_text(f"🎉 Ваш стиль работы: {result}")

        await show_profile(callback.message, callback.from_user.id)
        await state.clear()
    await callback.answer()